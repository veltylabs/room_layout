// swatchClass es la muestra de color de cada tipo de espacio, la misma en la leyenda y en la lista.
func swatchClass(roomType string) string {
	switch roomType {
	case RoomTypeShared:
		return clsSwatchShared
	case RoomTypeStore:
		return clsSwatchStore
	}
	return clsSwatchBox
}
